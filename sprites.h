// Draw a sprite at integer position (render-texture space). flip mirrors horizontally.
inline void drawSprite(const Sprite& s, float fx, float fy, bool flip, Color armour = WHITE, Color flash = BLANK, float alpha = 1.0f)
{
    int x = (int)fx, y = (int)fy;
    for (int j = 0; j < s.h; j++)
    {
        const char* row = s.rows[j];
        int w = (int)std::strlen(row);
        for (int i = 0; i < w; i++)
        {
            char ch = row[i];
            if (ch == '.')
                continue;
            Color c = paletteColor(ch, armour);
            if (flash.a)
                c = flash;
            c.a = (unsigned char)(c.a * alpha);
            DrawRectangle(x + (flip ? w - 1 - i : i), y + j, 1, 1, c);
        }
    }
}

inline int spriteWidth(const Sprite& s) { return (int)std::strlen(s.rows[0]); }
