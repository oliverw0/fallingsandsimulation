def normalize():
    for name, rows in S.items():
        w = max(len(r) for r in rows)
        S[name] = [r + '.' * (w - len(r)) for r in rows]


def check():
    normalize()
    ok = True
    for name, rows in S.items():
        w = len(rows[0])
        for i, r in enumerate(rows):
            if len(r) != w:
                print(f"{name} row {i} width {len(r)} != {w}: {r!r}")
                ok = False
            for ch in r:
                if ch != '.' and ch not in PAL:
                    print(f"{name} row {i} unknown char {ch!r}")
                    ok = False
    return ok


def preview(path, scale=8):
    from PIL import Image
    names = list(S)
    cellw = max(len(S[n][0]) for n in names) + 4
    cellh = max(len(S[n]) for n in names) + 4
    cols = 6
    rows = (len(names) + cols - 1) // cols
    im = Image.new('RGB', (cols * cellw, rows * cellh), (24, 22, 30))
    for k, n in enumerate(names):
        ox, oy = (k % cols) * cellw + 2, (k // cols) * cellh + 2 + (cellh - 4 - len(S[n]))
        for y, r in enumerate(S[n]):
            for x, ch in enumerate(r):
                if ch == '.':
                    continue
                c = PAL[ch]
                if len(c) == 4:
                    a = c[3] / 255
                    c = tuple(int(24 * (1 - a) + c[i] * a) for i in range(3))
                im.putpixel((ox + x, oy + y), c[:3])
    im = im.resize((im.width * scale, im.height * scale), Image.NEAREST)
    im.save(path)



TINTED = {'a': 1.0, 'A': 0.62, ';': 0.38, ',': 1.25}


def emit_palette():
    out = []
    for ch, c in PAL.items():
        if ch in TINTED:
            continue
        lit = "'\\''" if ch == "'" else f"'{ch}'"
        out.append(f"    case {lit}: return {{{c[0]}, {c[1]}, {c[2]}, {c[3] if len(c) == 4 else 255}}};")
    return "\n".join(out)


def emit_sprites():
    out = []
    for name, rows in S.items():
        body = ",\n".join(f'       "{r}"' for r in rows)
        out.append(f"SPRITE(SPR_{name},\n{body})")
    return "\n".join(out)



